import { readdir } from "node:fs/promises";
import { basename, join } from "node:path";
import { pathToFileURL } from "node:url";
import type { JSONSchema, Tool } from "../types.js";
import type { ToolRegistry } from "./registry.js";

export const TOOL_NAME_RE = /^[a-z][a-z0-9_]{2,39}$/;

export interface ToolDraft {
  name: string;
  description: string;
  parameters: JSONSchema;
  code: string;
}

/** Validates the arguments the model passed to create_tool. Throws on bad input. */
export function validateToolDraft(
  args: Record<string, unknown>,
  exists: (name: string) => boolean,
): ToolDraft {
  const { name, description, parameters, code } = args;

  if (typeof name !== "string" || !TOOL_NAME_RE.test(name)) {
    throw new Error("name must be 3–40 chars: lowercase letters, digits, underscores, starting with a letter");
  }
  if (exists(name)) throw new Error(`a tool named "${name}" already exists`);
  if (typeof description !== "string" || description.trim() === "") {
    throw new Error("description must be a non-empty string");
  }
  if (typeof parameters !== "object" || parameters === null || Array.isArray(parameters)) {
    throw new Error("parameters must be a JSON Schema object");
  }
  if (typeof code !== "string" || code.trim() === "") {
    throw new Error("code must be a non-empty function body that returns a string");
  }

  return { name, description, parameters: parameters as JSONSchema, code };
}

export function renderToolSource(d: ToolDraft): string {
  return [
    "// Generated by Connie. Runs locally with the user's permissions.",
    `export const description = ${JSON.stringify(d.description)};`,
    `export const parameters = ${JSON.stringify(d.parameters, null, 2)};`,
    "export default async function run(args) {",
    d.code,
    "}",
    "",
  ].join("\n");
}

/** Imports a tool module from disk and wraps it as a Tool. Cache-busted so edits take effect. */
export async function importToolModule(file: string): Promise<Tool> {
  const name = basename(file, ".mjs");
  const mod: Record<string, unknown> = await import(`${pathToFileURL(file).href}?t=${Date.now()}`);

  if (
    typeof mod.description !== "string" ||
    typeof mod.parameters !== "object" ||
    mod.parameters === null ||
    typeof mod.default !== "function"
  ) {
    throw new Error("module must export `description`, `parameters`, and a default run function");
  }

  const run = mod.default as (args: Record<string, unknown>) => Promise<unknown>;

  return {
    name,
    description: mod.description,
    parameters: mod.parameters as JSONSchema,
    run: async (args) => String(await run(args)),
  };
}

export async function loadDynamicTools(
  dir: string,
  registry: ToolRegistry,
): Promise<{ loaded: string[]; failed: { name: string; error: string }[] }> {
  const loaded: string[] = [];
  const failed: { name: string; error: string }[] = [];

  let files: string[];
  try {
    files = (await readdir(dir)).filter((f) => f.endsWith(".mjs"));
  } catch {
    return { loaded, failed }; // no tools dir yet
  }

  for (const file of files) {
    const name = basename(file, ".mjs");
    try {
      registry.register(await importToolModule(join(dir, file)));
      loaded.push(name);
    } catch (e) {
      failed.push({ name, error: e instanceof Error ? e.message : String(e) });
    }
  }
  return { loaded, failed };
}
